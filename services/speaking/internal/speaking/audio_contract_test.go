// SPEAK-EVAL-001 / 002 — the browser audio contract.
//
// The browser records with `new MediaRecorder(stream)` and no mimeType, so it
// emits an ENCODED container -- WebM/Opus on Chrome, Ogg/Opus on Firefox,
// MP4/AAC on Safari. Those bytes were forwarded to the speech sidecar labelled
//
//	filename="audio.pcm"
//	Content-Type: audio/pcm;rate=16000
//
// and the sidecar decodes anything matching audio/pcm with
// np.frombuffer(data, dtype=np.int16) -- reinterpreting a compressed Opus
// container as raw 16-bit samples. Every browser-originated practice score was
// computed on noise.
//
// It survived because the Go integration tests and the k6 load test construct
// REAL PCM, so they validate a contract the browser never produces. These tests
// use fixtures generated by ffmpeg in the exact formats browsers emit.

const (
	browserFixtureDir = "../../testdata/browser"

	webmFixture = "chrome_webm_opus.webm"
	oggFixture  = "firefox_ogg_opus.ogg"
	mp4Fixture  = "safari_mp4_aac.mp4"
	pcmFixture  = "reference_pcm_s16le_16k.raw"
)

func loadBrowserFixture(t *testing.T, name string) []byte {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(browserFixtureDir, name))
	if err != nil {
		t.Skipf("browser fixture %s missing; regenerate with services/speaking/testdata/browser/README.md: %v", name, err)
	}
	if len(data) == 0 {
		t.Fatalf("browser fixture %s is empty", name)
	}
	return data
}

// capturedUpload is what the speech sidecar actually received.
type capturedUpload struct {
	filename    string
	contentType string
	body        []byte
}

// sidecarSpy stands in for services/speech and records the multipart part the
// speaking service uploaded, so a test can assert on the declared format rather
// than on whatever the real sidecar chose to do with it.
func sidecarSpy(t *testing.T, captured *capturedUpload) *httptest.Server {
	t.Helper()
	return httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		mediaType, params, err := mime.ParseMediaType(r.Header.Get("Content-Type"))
		if err != nil || !strings.HasPrefix(mediaType, "multipart/") {
			t.Errorf("expected a multipart upload, got %q", r.Header.Get("Content-Type"))
			http.Error(w, "bad request", http.StatusBadRequest)
			return
		}

		reader := multipart.NewReader(r.Body, params["boundary"])
		part, err := reader.NextPart()
		if err != nil {
			t.Errorf("reading multipart part: %v", err)
			http.Error(w, "bad request", http.StatusBadRequest)
			return
		}
		defer part.Close()

		body, _ := io.ReadAll(part)
		captured.filename = part.FileName()
		captured.contentType = part.Header.Get("Content-Type")
		captured.body = body

		w.Header().Set("Content-Type", "application/json")
		_ = json.NewEncoder(w).Encode(map[string]any{
			"transcript": "fixture transcript",
			"duration_s": 6.0,
			"words": []map[string]any{
				{"word": "fixture", "start": 0.0, "end": 0.5, "probability": 0.9},
			},
		})
	}))
}

// TestBrowserAudioIsNotDeclaredAsPCM is the SPEAK-EVAL-001 regression test.
//
// It fails against the pre-fix service for the correct reason: the upload is
// labelled audio/pcm regardless of what the browser actually recorded.
func TestBrowserAudioIsNotDeclaredAsPCM(t *testing.T) {
	for _, tc := range []struct {
		name        string
		fixture     string
		declared    string
		wantInCT    string
		wantExtInFn string
	}{
		{"chrome webm/opus", webmFixture, "audio/webm;codecs=opus", "audio/webm", ".webm"},
		{"firefox ogg/opus", oggFixture, "audio/ogg;codecs=opus", "audio/ogg", ".ogg"},
		{"safari mp4/aac", mp4Fixture, "audio/mp4", "audio/mp4", ".m4a"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			audio := loadBrowserFixture(t, tc.fixture)

			var captured capturedUpload
			spy := sidecarSpy(t, &captured)
			defer spy.Close()

			client := newContractTestClient(t, spy.URL, tc.declared)
			client.transcribeAudio(audio)

			if strings.Contains(strings.ToLower(captured.contentType), "audio/pcm") {
				t.Fatalf(
					"upload declared Content-Type %q for %s audio.\n"+
						"The sidecar decodes anything matching audio/pcm with "+
						"np.frombuffer(dtype=int16), so a compressed container is "+
						"reinterpreted as raw samples and the transcript is noise.",
					captured.contentType, tc.declared,
				)
			}
			if !strings.Contains(strings.ToLower(captured.contentType), tc.wantInCT) {
				t.Errorf("Content-Type = %q, want it to contain %q", captured.contentType, tc.wantInCT)
			}
			if !strings.HasSuffix(strings.ToLower(captured.filename), tc.wantExtInFn) {
				t.Errorf(
					"filename = %q, want extension %q. A decoder that sniffs content "+
						"tolerates a wrong extension, but the filename is the first "+
						"thing a human reads when diagnosing this path.",
					captured.filename, tc.wantExtInFn,
				)
			}
			if !bytes.Equal(captured.body, audio) {
				t.Errorf("uploaded body differs from the recorded audio (%d vs %d bytes)", len(captured.body), len(audio))
			}
		})
	}
}

// TestDeclaredPCMStillUploadsAsPCM guards the other direction: the fix must not
// break a client that genuinely sends raw PCM, which is what the existing
// integration and load tests do.
func TestDeclaredPCMStillUploadsAsPCM(t *testing.T) {
	audio := loadBrowserFixture(t, pcmFixture)

	var captured capturedUpload
	spy := sidecarSpy(t, &captured)
	defer spy.Close()

	client := newContractTestClient(t, spy.URL, "audio/pcm;rate=16000")
	client.transcribeAudio(audio)

	if !strings.Contains(strings.ToLower(captured.contentType), "audio/pcm") {
		t.Fatalf("declared PCM was uploaded as %q; the raw-PCM path must still work", captured.contentType)
	}
}

// TestUndeclaredFormatIsRejectedNotGuessed — a session that never declared its
// format must not be scored. Guessing produces a number from unknown bytes,
// which is the defect with an extra step.
func TestUndeclaredFormatIsRejected(t *testing.T) {
	audio := loadBrowserFixture(t, webmFixture)

	var captured capturedUpload
	spy := sidecarSpy(t, &captured)
	defer spy.Close()

	client := newContractTestClient(t, spy.URL, "")
	client.transcribeAudio(audio)

	if captured.contentType != "" {
		t.Fatalf(
			"an undeclared format was uploaded as %q; the service must refuse to "+
				"transcribe audio whose encoding it does not know",
			captured.contentType,
		)
	}
	if err := waitForErrorFrame(t, client, 2*time.Second); err != nil {
		t.Fatalf("expected a typed error frame for the undeclared format: %v", err)
	}
}

// TestCompressedAudioDurationIsNotInferredFromByteCount — the second defect that
// was hidden behind the first.
//
// slo.go computes duration as bytes / (16000 * 2), i.e. it assumes raw PCM.
// Opus compresses roughly 10x, so on the browser path the transcription_ratio
// SLO (GOA-032, budget 0.6) has been dividing by a denominator ~10x too small.
// GOA-133 made the sidecar return duration_s; that is the number to use.
func TestCompressedAudioDurationIsNotInferredFromByteCount(t *testing.T) {
	audio := loadBrowserFixture(t, webmFixture)

	// The fixture is 6 seconds. Inferring from byte count treats every 32 bytes
	// as a millisecond, which for ~24kbps Opus is wildly wrong.
	inferred := pcmDurationMs(len(audio))
	const actualMs = 6000

	if inferred > actualMs/2 && inferred < actualMs*2 {
		t.Fatalf(
			"pcmDurationMs happened to land near the real duration (%d ms vs %d ms) "+
				"for this fixture, so this test cannot demonstrate the defect. "+
				"Regenerate the fixture at a different bitrate.",
			inferred, actualMs,
		)
	}

	t.Logf(
		"byte-count inference gives %d ms for %d ms of audio (%.1fx off) -- "+
			"duration must come from the sidecar's duration_s",
		inferred, actualMs, float64(actualMs)/float64(max64(inferred, 1)),
	)
}

func max64(a, b int64) int64 {
	if a > b {
		return a
	}
	return b
}

// newContractTestClient builds the minimum Client that can drive
// transcribeAudio: a buffered send channel nothing reads, a cancellable context,
// and the in-package mocks. No WebSocket is needed because every outbound frame
// goes through sendFrame into the channel, not through c.conn.
//
// declaredFormat is what the browser said it was recording. Passing "" models a
// session that never declared one.
func newContractTestClient(t *testing.T, speechURL, declaredFormat string) *Client {
	t.Helper()

	ctx, cancel := context.WithCancel(context.Background())
	t.Cleanup(cancel)

	c := &Client{
		id:             "contract-test",
		correlationID:  "contract-test",
		send:           make(chan WSMessage, 256),
		audioBuffer:    &bytes.Buffer{},
		ctx:            ctx,
		cancel:         cancel,
		speechURL:      speechURL,
		userID:         "contract-test-user",
		questionPrompt: "Describe a journey you took.",
		questionType:   "part2",
		startTime:      time.Now(),
		lastAudioAt:    time.Now(),
		llmClient:      &mockLLMClient{},
		ttsClient:      &mockTTSClient{},
		langfuseClient: &mockLangfuseClient{},
		dbRepo:         &mockDBRepo{},
	}
	// Mirror what readPump does with session_init: validate and store the
	// canonical media type, not the raw declaration. A test that stored the raw
	// string would exercise a code path production never takes.
	if declaredFormat != "" {
		normalized, err := normalizeAudioFormat(declaredFormat)
		if err != nil {
			t.Fatalf("fixture declares an unsupported format %q: %v", declaredFormat, err)
		}
		c.audioFormat = normalized
	}

	c.setOutcome("dropped")
	c.transcribeFn = c.transcribeAudio
	return c
}

// waitForErrorFrame drains the send channel looking for a typed error frame.
func waitForErrorFrame(t *testing.T, c *Client, within time.Duration) error {
	t.Helper()
	deadline := time.After(within)
	for {
		select {
		case msg := <-c.send:
			if msg.Type != 1 { // websocket.TextMessage
				continue
			}
			var frame struct {
				Type    string `json:"type"`
				Message string `json:"message"`
			}
			if err := json.Unmarshal(msg.Payload, &frame); err != nil {
				continue
			}
			if frame.Type == "error" {
				return nil
			}
		case <-deadline:
			return errors.New("no error frame arrived")
		}
	}
}
